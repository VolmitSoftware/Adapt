  private static void signature(ContentRegistrar registrar, String lead, String partner, Recipe recipe,
                                Function<MutationSlot, ? extends Signature<?>> factory) {
    registrar.signature(Id.adapt(lead), Id.adapt(partner), recipe, factory);
  }

  private static void text(ContentRegistrar registrar, String lead, String partner, Recipe recipe) {
    registrar.pairText(Id.adapt(lead), Id.adapt(partner), recipe, PairText.of(description(lead, partner, recipe)));
  }

  /** The partner's State also counts when it held in the last {@code seconds}. */
  private static void recentState(ContentRegistrar registrar, String lead, String partner, Recipe recipe,
                                  int seconds) {
    registrar.pairText(Id.adapt(lead), Id.adapt(partner), recipe,
        PairText.recentState(description(lead, partner, recipe), seconds));
  }

  private static void withBlocks(ContentRegistrar registrar, String lead, String partner, Recipe recipe,
                                 List<BlockKey> blocks) {
    registrar.pairText(Id.adapt(lead), Id.adapt(partner), recipe,
        PairText.of(description(lead, partner, recipe)).withBlocks(blocks));
  }

  private static Text description(String lead, String partner, Recipe recipe) {
    return PairMessages.override(new MutationSlot(new SkillPair(Id.adapt(lead), Id.adapt(partner)), recipe));
  }

  private static BlockKey block(String skill, BlockSlot slot) {
    return new BlockKey(Id.adapt(skill), slot);
  }
