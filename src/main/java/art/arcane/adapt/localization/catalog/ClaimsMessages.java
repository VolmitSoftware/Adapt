  public static TextKey error(ClaimException.Reason reason) {
    return switch (reason) {
      case FOUNDING_REQUIRED -> ERROR_FOUNDING_REQUIRED;
      case FORTIFICATION_REQUIRED -> ERROR_FORTIFICATION_REQUIRED;
      case HOMESTEAD_REQUIRED -> ERROR_HOMESTEAD_REQUIRED;
      case ALREADY_MEMBER -> ERROR_ALREADY_MEMBER;
      case CITY_NOT_FOUND -> ERROR_CITY_NOT_FOUND;
      case NOT_FOUNDER -> ERROR_NOT_FOUNDER;
      case WORLD_DENIED -> ERROR_WORLD_DENIED;
      case EXCLUDED_AREA -> ERROR_EXCLUDED_AREA;
      case LAND_OCCUPIED -> ERROR_LAND_OCCUPIED;
      case NOT_ADJACENT -> ERROR_NOT_ADJACENT;
      case CAPACITY_REACHED -> ERROR_CAPACITY_REACHED;
      case MEMBER_CAPACITY_REACHED -> ERROR_MEMBER_CAPACITY_REACHED;
      case ALREADY_HAS_PLOT -> ERROR_ALREADY_HAS_PLOT;
      case PLOT_OUTSIDE_CITY -> ERROR_PLOT_OUTSIDE_CITY;
      case PLOT_OVERLAP -> ERROR_PLOT_OVERLAP;
      case MAIN_ANCHOR_OVERLAP -> ERROR_MAIN_ANCHOR_OVERLAP;
      case INVITATION_MISSING -> ERROR_INVITATION_MISSING;
      case INVITATION_EXPIRED -> ERROR_INVITATION_EXPIRED;
      case NOT_MEMBER -> ERROR_NOT_MEMBER;
      case FOUNDER_CANNOT_LEAVE -> ERROR_FOUNDER_CANNOT_LEAVE;
      case INVALID_NAME -> ERROR_INVALID_NAME;
    };
  }

