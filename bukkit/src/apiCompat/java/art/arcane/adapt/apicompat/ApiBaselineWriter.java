package art.arcane.adapt.apicompat;

import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldNode;
import org.objectweb.asm.tree.InnerClassNode;
import org.objectweb.asm.tree.MethodNode;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.Deque;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Writes the baseline from the pre-port runtime jar and a scope file. Scope lines: {@code include <class glob>} adds
 * every public type matching the glob; {@code exclude <class glob> <member name regex> [descriptor regex]} drops
 * members that are Adapt internals. Globs use {@code *} within a package segment and {@code **} across segments.
 */
public final class ApiBaselineWriter {
  private static final Pattern REFERENCE = Pattern.compile("L(art/arcane/adapt/[^;<]+)[;<]");
  private static final String ADAPT = "art/arcane/adapt/";

  private ApiBaselineWriter() {
  }

  public static void main(String[] args) throws IOException {
    if (args.length != 3) {
      throw new IllegalArgumentException("usage: ApiBaselineWriter <pre-port runtime jar> <scope file> <baseline>");
    }
    Path jar = Path.of(args[0]);
    Map<String, ClassNode> classes = ApiBaseline.classes(jar, ClassReader.SKIP_CODE);
    Scope scope = Scope.read(Path.of(args[1]));

    Set<String> checked = new TreeSet<>();
    for (ClassNode node : classes.values()) {
      if (scope.includes(node.name) && visible(node, classes)) {
        checked.add(node.name);
      }
    }

    List<ApiBaseline.MemberEntry> members = new ArrayList<>();
    Set<String> referenced = new LinkedHashSet<>();
    for (String name : checked) {
      ClassNode node = classes.get(name);
      collectName(referenced, node.superName);
      collect(referenced, node.signature);
      for (String face : node.interfaces) {
        collectName(referenced, face);
      }
      for (FieldNode field : node.fields) {
        if (linkable(field.access) && !scope.excludes(name, field.name, field.desc)) {
          members.add(new ApiBaseline.MemberEntry(false, name, ApiBaseline.relevant(field.access), field.name,
              field.desc, field.signature));
          collect(referenced, field.desc, field.signature);
        }
      }
      for (MethodNode method : node.methods) {
        if (linkable(method.access) && !method.name.equals("<clinit>")
            && !scope.excludes(name, method.name, method.desc)) {
          members.add(new ApiBaseline.MemberEntry(true, name, ApiBaseline.relevant(method.access), method.name,
              method.desc, method.signature));
          collect(referenced, method.desc, method.signature);
        }
      }
    }

    Set<String> shells = new TreeSet<>();
    Deque<String> pending = new ArrayDeque<>(referenced);
    pending.addAll(checked);
    while (!pending.isEmpty()) {
      String name = pending.poll();
      ClassNode node = classes.get(name);
      if (node == null) {
        continue;
      }
      if (!checked.contains(name) && shells.add(name)) {
        pending.add(name);
      }
      List<String> parents = new ArrayList<>(node.interfaces);
      if (node.superName != null) {
        parents.add(node.superName);
      }
      int nested = name.lastIndexOf('$');
      if (nested > 0) {
        parents.add(name.substring(0, nested));
      }
      for (String parent : parents) {
        if (parent.startsWith(ADAPT) && !checked.contains(parent) && !shells.contains(parent)) {
          pending.add(parent);
        }
      }
    }

    List<ApiBaseline.TypeEntry> types = new ArrayList<>();
    for (String name : checked) {
      types.add(type(true, classes.get(name)));
    }
    for (String name : shells) {
      types.add(type(false, classes.get(name)));
    }

    new ApiBaseline(types, members).write(Path.of(args[2]),
        "Pre-port public API of the Adapt Bukkit plugin (HEAD before the multi-platform port).\n"
            + "Generated by :bukkit:generateApiBaseline from " + jar.getFileName() + " and api-scope.txt; "
            + "checked by :bukkit:verifyPublicApiCompatibility.");
  }

  private static ApiBaseline.TypeEntry type(boolean checked, ClassNode node) {
    int innerAccess = -1;
    for (InnerClassNode inner : node.innerClasses) {
      if (inner.name.equals(node.name)) {
        innerAccess = ApiBaseline.relevant(inner.access);
      }
    }
    return new ApiBaseline.TypeEntry(checked, node.name, ApiBaseline.relevant(node.access), innerAccess,
        node.superName, List.copyOf(node.interfaces), node.signature);
  }

  private static boolean visible(ClassNode node, Map<String, ClassNode> classes) {
    if ((node.access & Opcodes.ACC_PUBLIC) == 0 || (node.access & Opcodes.ACC_SYNTHETIC) != 0) {
      return false;
    }
    for (InnerClassNode inner : node.innerClasses) {
      if (inner.name.equals(node.name)) {
        if (inner.outerName == null || (inner.access & Opcodes.ACC_PUBLIC) == 0) {
          return false;
        }
        ClassNode outer = classes.get(inner.outerName);
        return outer != null && visible(outer, classes);
      }
    }
    return true;
  }

  private static boolean linkable(int access) {
    return (access & (Opcodes.ACC_PUBLIC | Opcodes.ACC_PROTECTED)) != 0 && (access & Opcodes.ACC_SYNTHETIC) == 0;
  }

  private static void collect(Set<String> referenced, String... texts) {
    for (String text : texts) {
      if (text == null) {
        continue;
      }
      Matcher matcher = REFERENCE.matcher(text);
      while (matcher.find()) {
        referenced.add(matcher.group(1));
      }
    }
  }

  private static void collectName(Set<String> referenced, String name) {
    if (name != null && name.startsWith(ADAPT)) {
      referenced.add(name);
    }
  }

  private record Rule(Pattern owner, Pattern name, Pattern descriptor) {
  }

  private record Scope(List<Pattern> includes, List<Rule> excludes) {
    static Scope read(Path file) throws IOException {
      List<Pattern> includes = new ArrayList<>();
      List<Rule> excludes = new ArrayList<>();
      for (String raw : Files.readAllLines(file, StandardCharsets.UTF_8)) {
        String line = raw.strip();
        if (line.isEmpty() || line.startsWith("#")) {
          continue;
        }
        String[] parts = line.split("\\s+");
        switch (parts[0]) {
          case "include" -> includes.add(glob(parts[1]));
          case "exclude" -> excludes.add(new Rule(glob(parts[1]), Pattern.compile(parts[2]),
              Pattern.compile(parts.length > 3 ? parts[3] : ".*")));
          default -> throw new IOException("Unknown scope line: " + raw);
        }
      }
      return new Scope(includes, excludes);
    }

    boolean includes(String name) {
      for (Pattern include : includes) {
        if (include.matcher(name).matches()) {
          return true;
        }
      }
      return false;
    }

    boolean excludes(String owner, String name, String descriptor) {
      for (Rule rule : excludes) {
        if (rule.owner().matcher(owner).matches() && rule.name().matcher(name).matches()
            && rule.descriptor().matcher(descriptor).matches()) {
          return true;
        }
      }
      return false;
    }

    private static Pattern glob(String glob) {
      StringBuilder regex = new StringBuilder();
      for (int index = 0; index < glob.length(); index++) {
        char character = glob.charAt(index);
        if (character == '*') {
          if (index + 1 < glob.length() && glob.charAt(index + 1) == '*') {
            regex.append(".*");
            index++;
          } else {
            regex.append("[^/]*");
          }
        } else {
          regex.append(Pattern.quote(String.valueOf(character)));
        }
      }
      return Pattern.compile(regex.toString());
    }
  }
}
