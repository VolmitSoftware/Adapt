package art.arcane.adapt.testkit;

import art.arcane.adapt.platform.ContentAliases;
import art.arcane.adapt.platform.EngineFeature;
import art.arcane.adapt.platform.GameVersion;
import art.arcane.adapt.platform.RegistryKind;
import art.arcane.adapt.platform.value.Id;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.EnumMap;
import java.util.EnumSet;
import java.util.HashSet;
import java.util.LinkedHashSet;
import java.util.Map;
import java.util.Set;

/**
 * The vanilla registries and tag names of one Minecraft version, read from {@code registries/<version>.txt} (generated by the
 * server's data generator), answered the way an adapter for that version must: 26.x ids, with renamed ids found
 * through {@link ContentAliases}.
 */
public final class FakeGameContent {
  private static final Map<String, RegistryKind> SECTIONS = Map.ofEntries(
      Map.entry("item", RegistryKind.ITEM), Map.entry("block", RegistryKind.BLOCK),
      Map.entry("entity_type", RegistryKind.ENTITY_TYPE), Map.entry("sound", RegistryKind.SOUND),
      Map.entry("particle", RegistryKind.PARTICLE), Map.entry("effect", RegistryKind.EFFECT),
      Map.entry("enchantment", RegistryKind.ENCHANTMENT), Map.entry("attribute", RegistryKind.ATTRIBUTE),
      Map.entry("biome", RegistryKind.BIOME), Map.entry("damage_type", RegistryKind.DAMAGE_TYPE),
      Map.entry("potion", RegistryKind.POTION));

  private static final String TAG_SECTION = "tag/";

  private final GameVersion version;
  private final Set<EngineFeature> features;
  private final Map<RegistryKind, Set<Id>> nativeIds;
  private final Map<RegistryKind, Set<Id>> tags;

  private FakeGameContent(GameVersion version, Set<EngineFeature> features, Map<RegistryKind, Set<Id>> nativeIds,
      Map<RegistryKind, Set<Id>> tags) {
    this.version = version;
    this.features = features;
    this.nativeIds = nativeIds;
    this.tags = tags;
  }

  public static FakeGameContent v1_20_1() {
    return load("1.20.1", EnumSet.noneOf(EngineFeature.class));
  }

  public static FakeGameContent v1_21_1() {
    return load("1.21.1", EnumSet.of(EngineFeature.ITEM_DATA_COMPONENTS, EngineFeature.DATA_DRIVEN_ENCHANTMENTS,
        EngineFeature.DISPLAY_TELEPORT_INTERPOLATION, EngineFeature.TICK_RATE_MANAGER, EngineFeature.ITEM_STACK_LIMITS));
  }

  public static FakeGameContent v26_1_2() {
    return load("26.1.2", EnumSet.allOf(EngineFeature.class));
  }

  public static FakeGameContent v26_2() {
    return load("26.2", EnumSet.allOf(EngineFeature.class));
  }

  public static FakeGameContent v26_3() {
    return load("26.3", EnumSet.allOf(EngineFeature.class));
  }

  private static FakeGameContent load(String name, Set<EngineFeature> features) {
    Map<RegistryKind, Set<Id>> ids = new EnumMap<>(RegistryKind.class);
    Map<RegistryKind, Set<Id>> tags = new EnumMap<>(RegistryKind.class);
    try (InputStream stream = FakeGameContent.class.getResourceAsStream("/registries/" + name + ".txt")) {
      if (stream == null) {
        throw new IllegalStateException("Missing registry snapshot for " + name);
      }
      BufferedReader reader = new BufferedReader(new InputStreamReader(stream, StandardCharsets.UTF_8));
      Set<Id> section = null;
      for (String line = reader.readLine(); line != null; line = reader.readLine()) {
        String trimmed = line.trim();
        if (trimmed.isEmpty() || trimmed.startsWith("#")) {
          continue;
        }
        if (trimmed.startsWith("[")) {
          String header = trimmed.substring(1, trimmed.length() - 1);
          boolean tag = header.startsWith(TAG_SECTION);
          RegistryKind kind = SECTIONS.get(tag ? header.substring(TAG_SECTION.length()) : header);
          if (kind == null) {
            throw new IllegalStateException("Unknown registry section " + trimmed + " in " + name);
          }
          section = new HashSet<>();
          (tag ? tags : ids).put(kind, section);
          continue;
        }
        section.add(Id.minecraft(trimmed));
      }
    } catch (IOException failure) {
      throw new UncheckedIOException(failure);
    }
    return new FakeGameContent(GameVersion.parse(name), Set.copyOf(features), ids, tags);
  }

  public GameVersion version() {
    return version;
  }

  public boolean supports(EngineFeature feature) {
    return features.contains(feature);
  }

  public boolean exists(RegistryKind kind, Id id) {
    Set<Id> registered = nativeIds.getOrDefault(kind, Set.of());
    return ContentAliases.resolve(kind, id, registered::contains) != null;
  }

  /** True when the version's bundled data pack defines the tag for this registry. */
  public boolean hasTag(RegistryKind kind, Id tag) {
    return tags.getOrDefault(kind, Set.of()).contains(tag);
  }

  /** Every id of the kind under its 26.x name. */
  public Set<Id> ids(RegistryKind kind) {
    Set<Id> modern = new LinkedHashSet<>();
    for (Id id : nativeIds.getOrDefault(kind, Set.of())) {
      if (ContentAliases.modern(kind, id).isEmpty()) {
        modern.add(id);
      } else {
        modern.addAll(ContentAliases.modern(kind, id));
      }
    }
    return modern;
  }
}
